// Generates supabase/seed_gyms.sql from the existing static data files plus
// scripts/real-gyms.js. Run with `node scripts/generate-seed-sql.js`, then
// paste the output file's contents into the Supabase SQL editor and run it
// (once, after supabase/002_gyms_and_accounts.sql).
const fs = require('fs');
const path = require('path');

const gymsJson = require('../data/gyms.json');
const gymsHu = require('../data/gyms.hu.json');
const realGyms = require('./real-gyms.js');

function sqlString(value) {
  if (value === null || value === undefined || value === '') return 'null';
  return `'${String(value).replace(/'/g, "''")}'`;
}

function sqlNumber(value) {
  return value === null || value === undefined ? 'null' : String(value);
}

function sqlBool(value) {
  return value ? 'true' : 'false';
}

function sqlTextArray(arr) {
  if (!arr || arr.length === 0) return 'null';
  const items = arr.map((v) => `"${String(v).replace(/"/g, '\\"')}"`).join(',');
  return `'{${items}}'`;
}

function sqlJsonb(value) {
  if (value === null || value === undefined) return 'null';
  return `'${JSON.stringify(value).replace(/'/g, "''")}'::jsonb`;
}

function gymInsert(g) {
  return `insert into gyms (
  id, name, sport, address, lat, lng, description, website, tags,
  first_training_info, equipment_needed, intensity_level, schedule,
  district, phone, email, facebook, instagram, price_from, price_note,
  is_demo, claimed, source_url
) values (
  ${sqlString(g.id)}, ${sqlString(g.name)}, ${sqlTextArray(g.sport)}, ${sqlString(g.address)},
  ${sqlNumber(g.lat)}, ${sqlNumber(g.lng)}, ${sqlString(g.description ?? '')}, ${sqlString(g.website ?? '')},
  ${sqlTextArray(g.tags)}, ${sqlString(g.firstTrainingInfo)}, ${sqlString(g.equipmentNeeded)},
  ${sqlString(g.intensityLevel)}, ${sqlJsonb(g.schedule)}, ${sqlNumber(g.district)},
  ${sqlString(g.phone)}, ${sqlString(g.email)}, ${sqlString(g.facebook)}, ${sqlString(g.instagram)},
  ${sqlNumber(g.priceFrom)}, ${sqlString(g.priceNote)}, ${sqlBool(g.isDemo)}, ${sqlBool(g.claimed)},
  ${sqlString(g.sourceUrl)}
)
on conflict (id) do nothing;`;
}

function translationInsert(gymId, lang, tr) {
  if (!tr) return null;
  return `insert into gym_translations (gym_id, lang, description, first_training_info, equipment_needed, price_note)
values (${sqlString(gymId)}, ${sqlString(lang)}, ${sqlString(tr.description)}, ${sqlString(tr.firstTrainingInfo)}, ${sqlString(tr.equipmentNeeded)}, ${sqlString(tr.priceNote)})
on conflict (gym_id, lang) do nothing;`;
}

const lines = [];
lines.push('-- Generated by scripts/generate-seed-sql.js — do not hand-edit, regenerate instead.');
lines.push('-- Run once in the Supabase SQL editor, after 002_gyms_and_accounts.sql.\n');

lines.push('-- ─────────────────────────── Demo gyms (fictional showcase data) ───────────────────────────\n');
for (const g of gymsJson) {
  lines.push(gymInsert({ ...g, isDemo: true, claimed: false }));
  const tr = translationInsert(g.id, 'hu', gymsHu[g.id]);
  if (tr) lines.push(tr);
  lines.push('');
}

lines.push('-- ─────────────────────────── Real, researched gyms ───────────────────────────\n');
for (const g of realGyms) {
  lines.push(gymInsert({ ...g, isDemo: false, claimed: false }));
  lines.push('');
}

const outPath = path.join(__dirname, '..', 'supabase', 'seed_gyms.sql');
fs.writeFileSync(outPath, lines.join('\n') + '\n', 'utf8');
console.log(`Wrote ${outPath}`);
console.log(`${gymsJson.length} demo gyms + ${realGyms.length} real gyms.`);
